# active_learning.py
"""
Active learning for the L-level Bayesian MF-RFF model `MF_RFF_bayes`, following
Heo & Sung, "Active Learning for a Recursive Non-Additive Emulator for Multi-Fidelity
Computer Experiments" (Technometrics, 2025), Section 4.

Levels are 0-indexed here (paper level l  <->  code level l-1). T is the target level
(default: the top level L-1).

ALD (Sec. 4.1)
    The latent predictive variance at the target is decomposed by the iterated law of
    total variance into the contribution of each level's emulator W_l:

        sigma_T^2(x) = sum_{l=0}^{T} V_l(x),
        V_l(x)       = E_{W_<l} [ Var_{W_l} ( g_l(x) | W_<l ) ],
        g_l(x)       = E[ f_T(x) | W_0, ..., W_l, data ],   g_T = f_T.

    Equivalently V_l = Var(g_l) - Var(g_{l-1}) with Var(g_{-1}) = 0.
    Next run:  (l*, x*) = argmax_{l, x}  V_l(x) / sum_{j<=l} C_j,
    and (nested design) f_0, ..., f_{l*} are all evaluated at x*.

ALM (Sec. 4.2)
    (l*, x*) = argmax_{l, x}  sigma_l^2(x) / sum_{j<=l} C_j,  with sigma_l^2 the latent
    predictive variance of level l itself.

How each V_l is computed in this model (cut posterior, coupled trajectories):
  * V_T     = E_s[ E[sigma_T^2|s] h_T,s(x) ]           (= predict()['var_weights'] at T)
  * Var(g_{T-1}) = Var_s( mu_T,s(x) )                   (= predict()['var_prop']    at T)
    The top level's weights are integrated analytically, so for L = 2 the decomposition
    is exact and needs no extra sampling.
  * Var(g_l), l <= T-2: nested Monte Carlo. Outer draws are stored trajectories of levels
    0..l; for each, `n_inner` fresh draws of levels l+1..T-1 are generated by refitting the
    cut posterior of those levels on the drawn lower-level trajectory, and the top level
    enters only through its analytic conditional mean. The finite-inner-sample bias of the
    variance of the inner means is removed (one-way ANOVA estimator).

Differences from the paper that are forced by the model:
  * The paper conditions W_l on f_{l-1}(x) only, which suffices because nested noise-free
    designs make f_{l-1} known at X_l. Here level-l's posterior depends on the whole
    lower-level trajectory (including its values at the higher-level training inputs), so
    "the randomness of W_l" is the cut posterior of level-l's weights and noise variance.
  * Variances are latent (no observation noise), so they are comparable across levels.
  * x is optimised over a candidate set, not by L-BFGS-B.
"""
from dataclasses import dataclass, field
import warnings

import numpy as np
from scipy.stats import qmc

from features_full import phi
from rff_linear_algebra import parameter_bayes, sample_weights_bayes, leverage_bayes
import scipy.linalg as sla


# =====================================================================
# 0. Small helpers
# =====================================================================
def _as_2d(X, d):
    X = np.asarray(X, dtype=float)
    if X.ndim == 1:
        X = X.reshape(-1, d) if d > 1 else X.reshape(-1, 1)
    if X.shape[1] != d:
        raise ValueError(f"X has {X.shape[1]} columns; expected d={d}.")
    return X


def candidate_set(d, n, seed=None):
    """Scrambled Sobol candidates in [0, 1]^d (n rounded up to a power of two)."""
    m = max(1, int(np.ceil(np.log2(n))))
    return qmc.Sobol(d=d, scramble=True, seed=seed).random_base2(m)


def _centred_data(model, X_list, y_list):
    """Returns training inputs and centred outputs exactly as fit() used them."""
    if len(X_list) != model.L or len(y_list) != model.L:
        raise ValueError(f"X_list and y_list must have {model.L} entries (the data the model was fit on).")
    Xs, ycs = [], []
    for k in range(model.L):
        Xk = _as_2d(X_list[k], model.d)
        yk = np.asarray(y_list[k], dtype=float).reshape(-1, 1)
        if Xk.shape[0] != model.N[k] or abs(float(yk.mean()) - model.y_mean[k]) > 1e-8 * (1 + abs(model.y_mean[k])):
            raise ValueError(f"Level {k} data differ from the data the model was fit on; refit first.")
        Xs.append(Xk)
        ycs.append(yk - model.y_mean[k])
    return Xs, ycs


# =====================================================================
# 1. Stored-chain quantities (identical to what predict() computes)
# =====================================================================
def _stored_chain(model, X, idx, upto):
    """
    Propagates stored trajectories `idx` through levels 0..upto at X.
    Returns (Z, mu_top, v_top): latent draws Z at level `upto` (N, B), plus the conditional
    mean and own-level weight variance of level `upto` given the lower trajectory.
    """
    a = model.a_prior
    phi0 = phi(X, model.omega[0])
    if upto == 0:
        h0 = leverage_bayes(phi0, model.L0, model.phi0_train, model.Sigma_inv[0]).reshape(-1, 1)
        noise0 = model.Q0 / (model.N[0] + 2.0 * a - 2.0)
        return phi0 @ model.W[0][idx].T, phi0 @ model.beta0_hat, noise0 * h0

    Z = phi0 @ model.W[0][idx].T
    for lvl in range(1, upto + 1):
        W, cache = model.W[lvl][idx], model.level_cache[lvl]
        last = lvl == upto
        if model.linear[lvl]:
            p = model.p[lvl]
            phi_l = phi(X, model.omega[lvl])
            if last:
                h_base = leverage_bayes(phi_l, cache['L_base'], cache['phi_cache_base'], cache['prec_base'])
                diff_F = Z - phi_l @ cache['B_F'][:, idx]
                H = h_base[:, None] + diff_F ** 2 / cache['a_vec'][idx][None, :]
                mu = phi_l @ cache['Beta_hat'][:, idx] + Z * cache['rho_hat'][idx][None, :]
            Z = phi_l @ W[:, :p].T + Z * W[:, p][None, :]
        else:
            proj = X @ model.omega[lvl][:, :model.d].T
            Z_new = np.empty_like(Z)
            if last:
                H, mu = np.empty_like(Z), np.empty_like(Z)
            for j, s in enumerate(idx):
                psi = model._nl_design_from_proj(lvl, proj, Z[:, [j]])
                Z_new[:, j] = psi @ W[j]
                if last:
                    mu[:, j] = (psi @ cache['gamma_hat'][s]).ravel()
                    H[:, j] = leverage_bayes(psi, cache['L_chol'][s], cache['psi_train'][s], model.Sigma_inv[lvl])
            Z = Z_new
    noise = model.Q[upto][idx] / (model.N[upto] + 2.0 * a - 2.0)
    return Z, mu, noise[None, :] * H


# =====================================================================
# 2. Cut posterior of one level given arbitrary lower-level trajectories
# =====================================================================
def _level_given_lower(model, k, X_tr, y_tr, F_tr, X_q, F_q, rng, sample):
    """
    Refits level k (>= 1) on each column of F_tr (lower-level latent values at X_k) and
    returns at X_q either the conditional posterior mean (sample=False) or one joint
    posterior draw of (sigma_k^2, w_k) per column (sample=True). Same algebra as fit().
    """
    B = F_tr.shape[1]
    N_k, p = X_tr.shape[0], model.p[k]
    a_N = model.a_prior + N_k / 2.0
    out = np.empty((X_q.shape[0], B))

    if model.linear[k]:
        lam = model.lam[k]
        prec = np.full(p, lam)
        phi_tr, phi_q = phi(X_tr, model.omega[k]), phi(X_q, model.omega[k])
        beta0, _, L_base = parameter_bayes(phi_tr, y_tr, mu=np.zeros((p, 1)), Sigma=prec)
        if p <= N_k:
            B_F = sla.solve_triangular(L_base, sla.solve_triangular(
                L_base, phi_tr.T @ F_tr, lower=True, check_finite=False),
                lower=True, trans='T', check_finite=False)
            u_y = y_tr - phi_tr @ beta0
            U = F_tr - phi_tr @ B_F
            phi_cache = None
        else:
            v_all = sla.solve_triangular(L_base, np.hstack([y_tr, F_tr]), lower=True, check_finite=False)
            u_all = sla.solve_triangular(L_base, v_all, lower=True, trans='T', check_finite=False)
            u_y, U = u_all[:, :1], u_all[:, 1:]
            B_F = (phi_tr.T @ U) / lam
            phi_cache = phi_tr
        a_vec = 1.0 / model.tau + np.sum(F_tr * U, axis=0)
        uty = (F_tr.T @ u_y).ravel()
        rho_hat = uty / a_vec
        Beta_hat = beta0 - B_F * rho_hat[None, :]
        if not sample:
            return phi_q @ Beta_hat + F_q * rho_hat[None, :]
        Q = np.maximum(0.0, float((y_tr.T @ u_y).item()) - uty ** 2 / a_vec) + 2.0 * model.b_prior
        sig2 = 1.0 / rng.gamma(shape=a_N, scale=2.0 / Q)
        rho = rho_hat + np.sqrt(sig2 / a_vec) * rng.standard_normal(B)
        d_beta = sample_weights_bayes(np.zeros((p, 1)), L_base, sig2, phi_cache, prec, rng).T
        Beta = Beta_hat - B_F * (rho - rho_hat)[None, :] + d_beta
        return phi_q @ Beta + F_q * rho[None, :]

    omega_x = model.omega[k][:, :model.d]
    proj_tr, proj_q = X_tr @ omega_x.T, X_q @ omega_x.T
    Sig = model.Sigma_inv[k]
    for b in range(B):
        psi_tr = model._nl_design_from_proj(k, proj_tr, F_tr[:, [b]])
        psi_q = model._nl_design_from_proj(k, proj_q, F_q[:, [b]])
        gam, Q_raw, Lc = parameter_bayes(psi_tr, y_tr, mu=model.mu[k], Sigma=Sig)
        if not sample:
            out[:, b] = (psi_q @ gam).ravel()
            continue
        sig2 = 1.0 / rng.gamma(shape=a_N, scale=2.0 / (Q_raw + 2.0 * model.b_prior))
        w = sample_weights_bayes(gam, Lc, np.array([sig2]),
                                 psi_tr if psi_tr.shape[1] > psi_tr.shape[0] else None, Sig, rng).ravel()
        out[:, b] = psi_q @ w
    return out


# =====================================================================
# 3. ALD variance decomposition
# =====================================================================
@dataclass
class ALDDecomposition:
    V: np.ndarray            # (N, T+1) raw contributions V_l(x) (MC noise can make them slightly < 0)
    total: np.ndarray        # (N,)     latent predictive variance of level T (= sum of V over l)
    var_g: np.ndarray        # (N, T+1) Var(g_l), l = 0..T  (non-decreasing in l up to MC error)
    target: int


def _var_g_nested(model, Xs, ycs, X_cand, l, T, n_outer, n_inner, rng):
    """Unbiased nested-MC estimate of Var(g_l)(x) = Var( E[f_T(x) | W_0..W_l] ), l <= T-2."""
    N = X_cand.shape[0]
    blocks = [X_cand] + [Xs[k] for k in range(l + 1, T + 1)]
    starts = np.cumsum([0] + [b.shape[0] for b in blocks])
    sl = {k: slice(starts[i + 1], starts[i + 2]) for i, k in enumerate(range(l + 1, T + 1))}
    X_all = np.vstack(blocks)

    outer = rng.choice(model.samples, size=min(n_outer, model.samples), replace=False)
    Z, _, _ = _stored_chain(model, X_all, outer, upto=l)
    Z = np.repeat(Z, n_inner, axis=1)                                     # (N_all, n_outer*n_inner)

    for k in range(l + 1, T):
        Z = _level_given_lower(model, k, Xs[k], ycs[k], Z[sl[k]], X_all, Z, rng, sample=True)
    G = _level_given_lower(model, T, Xs[T], ycs[T], Z[sl[T]], X_cand, Z[:N], rng, sample=False)

    G = G.reshape(N, len(outer), n_inner)
    between = np.var(G.mean(axis=2), axis=1, ddof=1)
    within = np.mean(np.var(G, axis=2, ddof=1), axis=1)
    return between - within / n_inner


def ald_decomposition(model, X_list, y_list, X_cand, *, target=None, n_outer=64, n_inner=16, seed=None):
    """
    Heo-Sung decomposition sigma_T^2(x) = sum_l V_l(x) for target level T (default top).
    For T <= 1 it is exact (no sampling beyond the stored trajectories).
    """
    if model.L is None:
        raise RuntimeError("Fit the model first.")
    Xs, ycs = _centred_data(model, X_list, y_list)
    X_cand = _as_2d(X_cand, model.d)
    T = model.L - 1 if target is None else int(target) % model.L
    rng = np.random.default_rng(seed)
    N = X_cand.shape[0]
    all_idx = np.arange(model.samples)

    _, mu_T, v_T = _stored_chain(model, X_cand, all_idx, upto=T)
    var_g = np.zeros((N, T + 1))
    var_g[:, T] = np.var(mu_T, axis=1) + np.mean(v_T, axis=1)         # Var(f_T): total latent variance
    if T >= 1:
        var_g[:, T - 1] = np.var(mu_T, axis=1)                          # Var(E[f_T | W_<T])
    for l in range(T - 2, -1, -1):
        var_g[:, l] = _var_g_nested(model, Xs, ycs, X_cand, l, T, n_outer, n_inner, rng)

    V = np.diff(np.column_stack([np.zeros(N), var_g]), axis=1)
    return ALDDecomposition(V=V, total=var_g[:, T], var_g=var_g, target=T)


# =====================================================================
# 4. Acquisition (ALD and ALM)
# =====================================================================
@dataclass
class Acquisition:
    x: np.ndarray               # (d,)  next input
    level: int                  # l*    (0-indexed)
    eval_levels: list           # levels to run at x (0..l* for nested designs, [l*] otherwise)
    cost: float
    score: np.ndarray = field(repr=False)   # (N, n_levels) criterion on the candidate set
    detail: object = field(repr=False, default=None)
    index: int = -1


def acquire(model, X_list, y_list, X_cand, *, method='ald', costs=None, nested=True,
            target=None, n_outer=64, n_inner=16, seed=None):
    """
    One acquisition by the paper's ALD or ALM rule.
      method : 'ald' -> argmax_{l<=T, x} V_l(x) / cost_l
               'alm' -> argmax_{l, x}    sigma_l^2(x) / cost_l   (latent variance of level l)
      costs  : C_0, ..., C_{L-1}.
      nested : True (paper): cost_l = sum_{j<=l} C_j and all levels j <= l are run at x.
               False: cost_l = C_l and only level l is run (your non-nested setting).
    """
    method = method.lower()
    L = model.L
    X_cand = _as_2d(X_cand, model.d)
    C = np.ones(L) if costs is None else np.asarray(costs, dtype=float)
    if C.shape != (L,) or np.any(C <= 0):
        raise ValueError(f"costs must be {L} positive numbers.")
    cost_l = np.cumsum(C) if nested else C

    if method == 'ald':
        detail = ald_decomposition(model, X_list, y_list, X_cand, target=target,
                                   n_outer=n_outer, n_inner=n_inner, seed=seed)
        crit = np.maximum(detail.V, 0.0)
    elif method == 'alm':
        pred = model.predict(X_cand)
        crit = np.column_stack([(pred[l]['var_prop'] + pred[l]['var_weights']).ravel() for l in range(L)])
        detail = pred
    else:
        raise ValueError("method must be 'ald' or 'alm'.")

    score = crit / cost_l[None, :crit.shape[1]]
    i, l = np.unravel_index(int(np.argmax(score)), score.shape)
    ev = list(range(l + 1)) if nested else [int(l)]
    return Acquisition(x=X_cand[i].copy(), level=int(l), eval_levels=ev,
                       cost=float(C[ev].sum()), score=score, detail=detail, index=int(i))


# =====================================================================
# 5. Driver
# =====================================================================
def active_learning_loop(make_model, X_list, y_list, oracles, *, budget, costs=None, method='ald',
                         nested=True, n_cand=1024, seed=0, callback=None, **acq_kwargs):
    """
    Sequential loop: refit -> acquire one (x, level) -> evaluate -> repeat until the budget
    would be exceeded.  oracles[k](x) returns one (noisy) observation of level k at x.
    Returns (final model, X_list, y_list, history).
    """
    X_list = [np.array(X, dtype=float) for X in X_list]
    y_list = [np.asarray(y, dtype=float).reshape(-1) for y in y_list]
    d = X_list[0].shape[1]
    spent, history, it = 0.0, [], 0
    model = make_model().fit(X_list, y_list)
    while True:
        acq = acquire(model, X_list, y_list, candidate_set(d, n_cand, seed=seed + it),
                      method=method, costs=costs, nested=nested, seed=seed + it, **acq_kwargs)
        if callback is not None:
            callback(model, acq, it, spent)
        if spent + acq.cost > budget:
            break
        for k in acq.eval_levels:
            X_list[k] = np.vstack([X_list[k], acq.x[None, :]])
            y_list[k] = np.append(y_list[k], float(oracles[k](acq.x)))
        spent += acq.cost
        history.append({'it': it, 'spent': spent, 'x': acq.x, 'level': acq.level,
                        'eval_levels': acq.eval_levels})
        model = make_model().fit(X_list, y_list)
        it += 1
    return model, X_list, y_list, history